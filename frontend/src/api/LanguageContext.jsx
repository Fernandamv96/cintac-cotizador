const languageIndexes = { en: 0, ru: 1, zh: 2, ja: 3 };

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const stored = localStorage.getItem("cintac-language") || "es";
    return ["es", "en", "ru", "zh", "ja"].includes(stored) ? stored : "es";
  });

  useEffect(() => {
    localStorage.setItem("cintac-language", language);
    document.documentElement.lang = language;
    document.title = t("Cotizador de Importaciones — Cintac");
  }, [language]);

  function t(text, replacements = {}) {
    const translated = languageIndexes[language] === undefined
      ? text
      : translations[text]?.[languageIndexes[language]] || text;
    return Object.entries(replacements).reduce(
      (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
      translated
    );
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage debe usarse dentro de LanguageProvider.");
  return context;
}
